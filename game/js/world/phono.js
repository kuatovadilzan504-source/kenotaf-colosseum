/* ключ фонограммы механизма: вид, вариация, мини-страж, страж */
function phonoKey(e){if(e.isBoss)return 'boss_'+e.type;if(e.mini)return 'mini';return e.variantKey&&PHONO[e.variantKey]?e.variantKey:e.type;}
/* разобран — на полу под ним остаётся валик, если этот вид ещё не слушали */
function dropPhono(W,e){const gs=W.game.gs,k=phonoKey(e);if(!PHONO[k]||gs.flags['ph_'+k])return;
  if(W.interactables.some(i=>i.def.kind==='phono'&&i.def.key===k))return;
  let fy=W.room.h;for(const s of W.room.solids){if(s.hidden)continue;if(e.cx>=s.x&&e.cx<=s.x+s.w&&s.y>=e.cy-0.2&&s.y<fy)fy=s.y;}
  const name=e.mini?(e.eliteName||PHONO[k].n):PHONO[k].n;
  const def={kind:'phono',key:k,name,x:clamp(e.cx,1,W.room.w-1),y:fy,w:1.6,h:1.6};W.interactables.push(new Interactable(def,W));
  /* стражи: валик запоминается за залом — не пропадёт, если уйти, не прослушав */
  if(e.isBoss)gs.flags['phd_'+W.room.id]={key:k,name,x:def.x,y:def.y};}
function drawPhono(c,it,t){const x=it.x,y=it.y,p=0.5+0.5*Math.sin(t*3.2);
  c.save();c.translate(x,y-0.18);c.rotate(-0.25);
  const g=c.createLinearGradient(-0.3,-0.12,0.3,0.12);g.addColorStop(0,'#6d5416');g.addColorStop(0.5,'#e8c96a');g.addColorStop(1,'#6d5416');
  c.fillStyle=g;rr(c,-0.3,-0.12,0.6,0.24,0.08);c.fill();
  c.strokeStyle='rgba(40,28,10,.6)';c.lineWidth=0.015;for(let i=-0.22;i<0.25;i+=0.06){c.beginPath();c.moveTo(i,-0.11);c.lineTo(i,0.11);c.stroke();}
  c.restore();
  c.fillStyle=rgba('#bfefff',0.14*p);c.beginPath();c.arc(x,y-0.3,0.7,0,TAU);c.fill();
  it.world.game.renderer.glowAdd(x,y-0.3,0.7,'#9fe6ff',0.25+0.15*p);}
